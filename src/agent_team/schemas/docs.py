"""Markdown reference pages generated from the canonical JSON Schemas (build-order step 14).

One page per kind in `SCHEMAS`, plus an index, written to `docs/spec/` by
`agent-team schema docs`. Every page is rendered from `json_schema(kind)` alone,
so a page can only say what the exported schema says. `--check` compares the
committed pages with a fresh render; a test runs the same comparison, so the
pages cannot drift from the models.
"""

from pathlib import Path
from typing import Any

from agent_team.canonical import LAYOUT, REGISTRY
from agent_team.schemas import SCHEMAS, json_schema

INDEX = "README.md"

GENERATED_NOTE = (
    "<!-- Generated by `agent-team schema docs` from the JSON Schemas. Do not edit by hand: "
    "change the pydantic model, then re-run `agent-team schema docs --out docs/spec`. -->"
)

VALIDATOR_NOTE = (
    "This page is the JSON Schema's shape. `agent-team validate` checks the same shape through the pydantic "
    "model and also runs the model's own validators and the cross-file checks, which JSON Schema cannot express "
    "and this page does not list; read the source module for those."
)


def file_location(kind: str) -> str:
    """Where files of this kind live, from the layout `agent-team validate` walks."""
    for subdir, (layout_kind, pattern) in LAYOUT.items():
        if layout_kind == kind:
            return f"canonical/{subdir}/{pattern}"
    if kind == "registry":
        return REGISTRY.as_posix()
    return "not read from a file"


def source_module(kind: str) -> str:
    return "src/" + SCHEMAS[kind].__module__.replace(".", "/") + ".py"


def _code(text: Any) -> str:
    """An inline code span safe inside a Markdown table cell."""
    return "`" + str(text).replace("|", "\\|") + "`"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _anchor(name: str) -> str:
    return name.lower()


def _json(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if isinstance(value, str):
        return f'"{value}"'
    return str(value)


def type_of(node: dict[str, Any]) -> str:
    """A short human type for one schema node: `string`, `list of Node`, `map of string to A0 | A1`."""
    if "$ref" in node:
        name = node["$ref"].rsplit("/", 1)[-1]
        return f"[{name}](#{_anchor(name)})"
    if "const" in node:
        return _code(_json(node["const"]))
    if "enum" in node:
        return " \\| ".join(_code(_json(v)) for v in node["enum"])
    if "anyOf" in node:
        options = [o for o in node["anyOf"] if o.get("type") != "null"]
        rendered = " or ".join(type_of(o) for o in options)
        return rendered + " or null" if len(options) < len(node["anyOf"]) else rendered
    kind = node.get("type")
    if kind == "array":
        return "list of " + type_of(node.get("items", {}))
    if kind == "object":
        if "patternProperties" in node:
            ((pattern, value),) = node["patternProperties"].items()
            return f"map of key {_code(pattern)} to {type_of(value)}"
        if isinstance(node.get("additionalProperties"), dict):
            return "map of string to " + type_of(node["additionalProperties"])
        return "object"
    return str(kind) if kind else "any"


def _constraint_parts(node: dict[str, Any]) -> list[str]:
    parts = []
    if "pattern" in node:
        parts.append(f"pattern {_code(node['pattern'])}")
    for key, label in (("minLength", "min length"), ("maxLength", "max length"), ("minItems", "min items"),
                       ("maxItems", "max items"), ("minProperties", "min entries"), ("minimum", "minimum"),
                       ("maximum", "maximum")):  # fmt: skip
        if key in node:
            parts.append(f"{label} {node[key]}")
    names = node.get("propertyNames")
    if isinstance(names, dict):
        parts.extend(f"key {p}" for p in _constraint_parts(names))
    return parts


def constraints(node: dict[str, Any]) -> str:
    """Constraints on the node itself, its list items, its map values and its non-null option."""
    parts = _constraint_parts(node)
    if isinstance(node.get("items"), dict) and "$ref" not in node["items"]:
        parts.extend(f"each {p}" for p in _constraint_parts(node["items"]))
    for value in (node.get("patternProperties") or {}).values():
        if "$ref" not in value:
            parts.extend(f"each value {p}" for p in _constraint_parts(value))
    for option in node.get("anyOf", []):
        if option.get("type") != "null" and "$ref" not in option:
            parts.extend(_constraint_parts(option))
            if isinstance(option.get("items"), dict):
                parts.extend(f"each {p}" for p in _constraint_parts(option["items"]))
    return "; ".join(parts)


def fields_table(schema: dict[str, Any]) -> list[str]:
    properties: dict[str, Any] = schema.get("properties", {})
    if not properties:
        return ["No fields."]
    required = set(schema.get("required", []))
    lines = ["| Field | Type | Required | Default | Constraints | Description |", "| --- | --- | --- | --- | --- | --- |"]
    for name, node in properties.items():
        default = _code(_json(node["default"])) if "default" in node else ""
        lines.append(
            f"| {_code(name)} | {type_of(node)} | {'yes' if name in required else 'no'} | {default} | "
            f"{constraints(node)} | {_cell(node.get('description', ''))} |"
        )
    return lines


def render_kind(kind: str) -> str:
    """The reference page for one canonical kind."""
    schema = json_schema(kind)
    lines = [GENERATED_NOTE, "", f"# `{kind}`", ""]
    if schema.get("description"):
        lines += [schema["description"], ""]
    lines += [
        f"- Files: {_code(file_location(kind))}",
        f"- Model: {_code(schema['title'])} in {_code(source_module(kind))}",
        f"- JSON Schema: {_code(schema['$id'])} (`agent-team schema export {kind}`)",
        f"- Unknown keys: {'rejected' if schema.get('additionalProperties') is False else 'allowed'}",
        "",
        VALIDATOR_NOTE,
        "",
        "## Fields",
        "",
        *fields_table(schema),
    ]
    for name, definition in schema.get("$defs", {}).items():
        lines += ["", f"## {name}", ""]
        if definition.get("description"):
            lines += [definition["description"], ""]
        lines += fields_table(definition)
    return "\n".join(lines) + "\n"


def render_index() -> str:
    lines = [
        GENERATED_NOTE,
        "",
        "# Canonical file reference",
        "",
        "One page per canonical kind, generated from the JSON Schemas that `agent-team schema export` writes.",
        "`agent-team validate` checks every file under `canonical/` (and `routing/registry.yaml` beside it) against these.",
        "",
        "| Kind | Files | Page |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {_code(kind)} | {_code(file_location(kind))} | [{kind}.md]({kind}.md) |" for kind in SCHEMAS]
    return "\n".join(lines) + "\n"


def render_all() -> dict[str, str]:
    """Every page by file name: the index, then one `<kind>.md` per kind."""
    return {INDEX: render_index(), **{f"{kind}.md": render_kind(kind) for kind in SCHEMAS}}


def drift(out_dir: Path) -> list[str]:
    """How the pages in `out_dir` differ from a fresh render: missing, stale, or not generated."""
    pages = render_all()
    problems = []
    for name, text in pages.items():
        path = out_dir / name
        if not path.is_file():
            problems.append(f"{path}: missing")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{path}: out of date")
    if out_dir.is_dir():
        problems += [f"{p}: not generated from a schema" for p in sorted(out_dir.glob("*.md")) if p.name not in pages]
    return problems
